/**
  ******************************************************************************
  * @file    swd_selftest.h
  * @brief   **SWD 烧录自检**（B1）：不依赖 SPI Flash，单独验证 SWD 这一段能不能干活
  *
  * 背景：治具的固件仓库是 SPI2 上的 GD25Q128。如果这颗 MCU 的 SPI2 不可用
  *       （实测确实不可用，见 docs），"上传→烧录"整条链就断了。
  *       但烧录真正动手的是 SWD 两线，那一段和 SPI Flash 毫无关系，
  *       所以本模块用**内置图样**代替"从 Flash 取镜像"，把 SWD 这一段单独跑通：
  *
  *       连接（线复位/上电/选 AP）→ 暂停 → 擦 scratch 扇区 →
  *       写 4 KB 图样 → **SWD 回读逐字节比对** → 读 96-bit UID → 复位运行
  *
  * ⚠ 自检写的是 `DUT_SCRATCH_ADDR`（F4 sector 11，最后一个 128 KB 扇区），
  *    **在 Boot/App 分区之外** → 板上原有的 FOC 固件不受影响，随时可跑。
  *
  * 非阻塞：`SST_Step()` 每轮只做一小步，由 `APP_Run()` 推进（与 `SWDP_Step()` 同一套路），
  *         擦除一个 128 KB 扇区约 1~1.5 秒，期间主循环照常响应 PC。
  ******************************************************************************
  */
#ifndef __SWD_SELFTEST_H
#define __SWD_SELFTEST_H

#include <stdint.h>

/** 一次自检：启动状态机（立即返回，终态在 APP_Run 里回 ACK） */
void    SST_Start(void);

/** 推进一小步（由 APP_Run 每轮调用） */
void    SST_Step(void);

/** @retval 1 = 还在跑 */
uint8_t SST_Busy(void);

/**
  * @brief  取结果
  * @param  out 输出缓冲，**必须 16 字节**
  * @retval 状态码（同时写在 out[0]）
  *           0x00 OK（自检全过）  0x04 ERR_PROG（SWD/烧写失败）  0x05 ERR_TEST（回读不一致）
  * @note   out 布局（大端）：
  *           [0]      状态码
  *           [1]      阶段：1=连接 2=擦除 3=写 4=校验 5=读UID 0xFF=全部完成
  *           [2..3]   首个不符字节偏移（相对 scratch 区），0xFFFF = 无不符
  *           [4..7]   SWD IDCODE（期望 0x2BA01477）
  *           [8..9]   DBGMCU DEV_ID（期望 0x0413 = STM32F405）
  *           [10..11] 已写入字节数
  *           [12]     失败时线路上的**原始 SWD ACK**（ADIv5：01=OK 02=WAIT 04=FAULT 00=无应答）
  *           [13]     失败时的内部错误码 = (uint8_t)(-返回码)
  *           [14..15] 预留 0
  */
uint8_t SST_Result(uint8_t *out);

/**
  * @brief  **SWD 引脚活动测试**（阻塞约 7 秒，分两个阶段）
  * @param  out 输出缓冲，必须 16 字节
  * @note   为什么需要它：一次 SWD 连接尝试只有几十~几百微秒，万用表平均下来显示 ~0.01 V，
  *         容易被误判成"治具没输出"。本测试把 2 秒的持续方波 + 5 秒的固定低电平打出来，
  *         让万用表可以直接量"信号到底走到了哪一段"。
  *
  *         **两个阶段**（期间 PC 不要发别的命令）：
  *           阶段 1（第 0~2 秒）：SWCLK 输出方波（万用表可读约 0.9~1.6 V），
  *                              同时把 SWDIO 配成带上拉输入采样 8 次
  *           阶段 2（第 2~7 秒）：SWCLK 与 SWDIO **都驱动为低电平**
  *                              → 在**目标板那一端**量 SWDIO 焊盘：
  *                                  0 V    = 线是通的（我们的低电平压过目标内部上拉）
  *                                  ~3.3 V = 线没通到目标（只剩目标自己的上拉）
  *
  *         out 布局：
  *           [0]      状态（00 = 已执行）
  *           [1]      AFIO->MAPR 的 SWJ_CFG（**期望 4** = JTAG+SW 全关，脚才是普通 IO）
  *           [2]      PA13(DIO) 的 4bit 配置
  *           [3]      PA14(CLK) 的 4bit 配置（输出推挽 50MHz = 0x3）
  *           [4]      PA13 采样位图（采样点在 CLK 拉低之后：未短接 ≈0xFF，短接 ≈0x00）
  *           [5]      8 次采样中为高的次数（未短接 ≈8，短接 ≈0）
  *           [6..7]   方波周期数（低 16 位）
  *           [8]      **0xA5 = 本版标记**（说明含"阶段 2"）
  *           [9..15]  预留 0
  */
void SST_PinActivityTest(uint8_t *out);

/**
  * @brief  **SWD 速度扫描**（mode=2）：一次把 8 档位翻转速度全试一遍，看哪档能连上
  * @param  out 输出缓冲，必须 16 字节
  * @note   位翻转 SWD 在长飞线/无终端时，可能因为"太快"而完全握不上手；
  *         本测试依次用 延时 = 0/2/4/8/16/32/64/128 个空循环去跑 SWD_Connect。
  *         out 布局：
  *           [0]     状态 00
  *           [1..8]  8 档各自的结果：bit7=1 表示该档连接失败；低 3 位是当时读到的 ACK
  *                   （01=OK 02=WAIT 04=FAULT 00=无应答）
  *           [9]     **能连上的那一档的延时值**；0xFF = 8 档全失败
  *           [10..13] 第一次成功时的 IDCODE（全失败则 0）
  *           [14..15] 预留 0
  */
void SST_SpeedProbe(uint8_t *out);

/**
  * @brief  **连续连接尝试**（mode=4）：5 秒窗口内不停重试 SWD_Connect
  * @param  out 输出缓冲，必须 16 字节
  * @note   用来验证"是否必须**复位下连接**"：
  *           发命令后在这 5 秒内按住再松开被测板复位按钮（或断电重上电）——
  *             有一次成功 → 目标跑起来后占用了 SWD 脚，必须接 NRST 做复位下连接
  *             一次都不成功 → 与复位时机无关
  *         out 布局：
  *           [0]      状态 00
  *           [1]      `01` = 成功，`00` = 全失败
  *           [2..5]   IDCODE（成功时；F405 期望 `2B A0 14 77`）
  *           [6..7]   尝试次数（低 16 位）
  *           [8]      **`B6` = 本版标记**
  *           [9..15]  预留 0
  */
void SST_ConnectBurst(uint8_t *out);

/**
  * @brief  **AP 写事务波形捕捉**（mode=5）：抓"AP 写 TAR"那一笔的 24 拍 SWDIO 电平
  * @param  out 输出缓冲，必须 16 字节
  * @note   用于定位"连接通了但之后每一笔都 NO_ACK"：先跑连接/上电/MEM-AP 初始化，
  *         再手工发一笔 AP 写 TAR 请求头并抓 24 拍。
  *         out 布局：
  *           [0]      状态 00
  *           [1]      前置步骤结果：`00`=三步全过；`E1`=连接失败 `E2`=上电失败 `E3`=MEM-AP 失败
  *           [2..4]   24 拍位图（bit23 = 第一拍；前 3 位应是 ACK）
  *           [5]      常规路径读到的 ACK（原始 3 位）
  *           [6]      最后一笔请求头字节（应为 `8B`）
  *           [8]      `B6` 本版标记
  *           [7][9..15] 预留 0
  */
void SST_ApWriteCapture(uint8_t *out);

/**
  * @brief  **SWD 波形捕捉**（mode=3）：把"请求头之后 32 个时钟"的 SWDIO 电平抓回来
  * @param  out 输出缓冲，必须 16 字节
  * @note   没有示波器时用它判断"目标到底有没有驱动数据线"：
  *           目标活着 → 最高 3 位应是 ACK=`001`（位图以 1,0,0 开头），后面是 IDCODE 数据
  *           全是 1   → 那 32 拍里线上没人驱动（目标没认出请求头）
  *         out 布局：
  *           [0]      状态 00
  *           [1..4]   32 拍位图（bit31 = 第一拍，即 ACK 的 bit0）
  *           [5..15]  预留 0
  */
void SST_WaveCapture(uint8_t *out);

#endif /* __SWD_SELFTEST_H */
