/**
  ******************************************************************************
  * @file    cur_chk.h
  * @brief   ⑥ 相电流检测的**判据层**：治具读到的电流 vs 被测板自己读到的
  *
  * 任务 ⑥ 要回答的问题
  * ------------------
  * 被测板的电流采样链路（采样电阻 → 放大器 → ADC → 固件换算）对不对？
  * 做法：**让被测板真的通一个电流**（`DUT_CURRENT` 静态通流：上桥 A、下桥 B），
  * 治具自己采一遍它送出来的电流检测信号，再问被测板"你自己采到多少"，
  * 两边一比 —— 对得上，说明整条链路（含它的换算系数）是好的。
  *
  * 为什么用「通流前 / 通流中」的**差值**比，而不是比绝对值
  * ------------------------------------------------------
  * 1. 治具和被测板是**两套 ADC + 两套参考电压**，绝对值天然差一点；
  * 2. 更要紧的是：**被测板的电流放大器可能是中点偏置的**（零电流输出 1.65V 之类），
  *    也可能以 0V 为地（零电流输出 0V）—— 这个拓扑我们**还不知道**（`docs/15` 待确认项 D4）。
  *    比差值就把这两种拓扑统一了：零电流的偏置被减掉了，剩下的就是"电流引起的那个变化量"。
  *
  * 三个判据
  * --------
  *   ① **通流检查**：两边差值都小到几乎没有 → 电流根本没流起来（真故障，要判失败）；
  *   ② **一致性**：两边的差值之差 ≤ 容差 → 说明它们测的是同一个电流、换算也对得上；
  *   ③ **数据可用性**：任一侧数据不可用（快照无效 / 通道贴边 / DUT 没报）→ **不判**。
  *
  * ⚠ 与 ②④ 同一条规矩：**"不判"不等于"失败"**（数据不全时不能冤判）。
  *
  * 只 U1 用（判定只在 U1 做，同 measure 的既有原则）→ **不做两片副本**。
  ******************************************************************************
  */
#ifndef __CUR_CHK_H
#define __CUR_CHK_H

#include <stdint.h>
#include "measure.h"

/* ------------------------------------------------------------------ */
/* 1. 判据参数（上板按实测收紧）                                        */
/* ------------------------------------------------------------------ */
#ifndef CUR_CHK_TOL_MV
#define CUR_CHK_TOL_MV      30u     /* 一致性容差的绝对下限 */
#endif
#ifndef CUR_CHK_TOL_PCT
#define CUR_CHK_TOL_PCT     5u      /* 相对容差：按对侧差值算 */
#endif
#ifndef CUR_CHK_MIN_DELTA_MV
#define CUR_CHK_MIN_DELTA_MV 50u    /* 两边变化都小于这个 → 认为"没通上电流" */
#endif

/* 电流通道编号（与 MEAS_CH_CUR1/CUR2 对应；PC 侧的 mask 用同样的位） */
#define CUR_CHK_CH1         0u      /* 电流检测 1 → MEAS_CH_CUR1(7) */
#define CUR_CHK_CH2         1u      /* 电流检测 2 → MEAS_CH_CUR2(8) */
#define CUR_CHK_CH_COUNT    2u

/* ------------------------------------------------------------------ */
/* 2. 旗标                                                            */
/* ------------------------------------------------------------------ */
#define CUR_CHK_F_OK        0x0001u  /* 判定通过 */
#define CUR_CHK_F_NODATA    0x0002u  /* 数据不全 → **不判**（不是失败） */
#define CUR_CHK_F_NOSIGNAL  0x0004u  /* 电流没真的流起来（真故障） */
#define CUR_CHK_F_DEVIATION 0x0008u  /* 两边差超容差（真故障） */

/* ------------------------------------------------------------------ */
/* 3. 输入 / 输出                                                      */
/* ------------------------------------------------------------------ */
typedef struct {
    uint16_t jig_idle_mv;   /* 通流**之前**治具读到的 mV */
    uint16_t jig_on_mv;     /* 通流**之中**治具读到的 mV */
    uint16_t dut_idle_mv;   /* 通流之前被测板自己读到的 mV */
    uint16_t dut_on_mv;     /* 通流之中被测板自己读到的 mV */
    uint8_t  jig_ok;        /* 治具侧数据可用（快照有效 + 该通道没贴边） */
    uint8_t  dut_ok;        /* 被测板把这一路报上来了 */
} cur_chk_in_t;

typedef struct {
    int32_t  dj;            /* 治具的变化量（有符号：放大器拓扑未知，可能为负） */
    int32_t  dd;            /* 被测板的变化量 */
    int32_t  err;           /* dj − dd */
    uint32_t tol;           /* 本次用的容差 */
    uint16_t flags;         /* CUR_CHK_F_* */
} cur_chk_out_t;

/* ------------------------------------------------------------------ */
/* 4. API                                                             */
/* ------------------------------------------------------------------ */
/**
  * @brief  判一路电流
  * @retval 该路的 flags（CUR_CHK_F_*）；参数为空返回 0
  */
uint16_t CurChk_Judge(const cur_chk_in_t *in, cur_chk_out_t *out);

/**
  * @brief  从治具快照里取某一路电流的 mV
  * @param  snap  本片电压快照（可传 0）
  * @param  which CUR_CHK_CH1 / CH2
  * @param  mv    [out] 毫伏
  * @retval 1 = 可用；0 = 不可用（快照无效 / 通道贴边 / 参数不对）
  */
uint8_t  CurChk_TakeJig(const meas_snapshot_t *snap, uint8_t which, uint16_t *mv);

/** 人体可读的旗标文本（调试打印用；返回静态字符串） */
const char *CurChk_FlagText(uint16_t flags);

#endif /* __CUR_CHK_H */
