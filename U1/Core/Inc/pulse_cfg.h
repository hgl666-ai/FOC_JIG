/**
  ******************************************************************************
  * @file    pulse_cfg.h
  * @brief   输入捕获绑定：三相**主控驱动信号** → TIM3(CH2/CH1) + TIM1(CH1)
  *
  *   A 相 → TIM3_CH2 = PB5     ← MA_IN
  *   B 相 → TIM3_CH1 = PB4     ← MB_IN
  *   C 相 → TIM1_CH1 = PA8     ← MC_IN
  *
  * ⚠ **两片完全一样**：U1 和 U2 的 PB5/PB4/PA8 接在**同一组信号**上（原理图核过），
  *   所以本文件是**逐字节副本**，由回归脚本 `fc /b` 比对（改一份忘另一份会直接判失败）。
  *
  * 为什么两片测同一组（2026-10 改，见 docs/00 §3.5 / docs/12 §10）
  * ---------------------------------------------------------------
  * 原先 U1 配的是 `TIM4 ← PB6/PB7/PB8`，而那三个脚其实是**编码器座 CN2** 的 A/B/Z，
  * 不是电机输出端；`MA0_OUT` 组在硬件上**只有 ADC 通路、没有定时器通路**。
  * 所以原来"同一相两端（输入 vs 输出）对比"的前提不成立、比出来的结论没有物理意义。
  * 改成：**两片测同一组信号，做真冗余互比**（与 9 路 ADC 的交叉校验同构），
  * 电机输出端（④）改走 ADC 相电压：`V_平均 ≈ 占空比 × 母线电压`。
  * 编码器线（CN2 的 A/B/Z）留给 ⑤：U1 发脉冲、U2 采集做回环。
  *
  * 捕获方式：**单通道 + 每个边沿翻转极性**（`pulse_cap.c` 文件头有约定说明）。
  * （历史选择：当年为了省捕获通道才用单通道；改用 TIM3+TIM1 之后硬件 PWM 输入模式
  *   其实也放得下，但算法层、45B 线格式、测试都已按单通道做好，没有理由换。）
  ******************************************************************************
  */
#ifndef __PULSE_CFG_H
#define __PULSE_CFG_H

#include <stdint.h>
#include "pulse_cap.h"

/** 配好捕获并让定时器自由运行（上电初始化时调一次，此时**不采**） */
void    PULSE_CfgInit(void);

/** 开一个测量窗口：清时间戳、复位计数器、打开捕获中断 */
void    PULSE_CfgStart(uint16_t window_ms);

/** 关捕获（窗口未到也可强制停） */
void    PULSE_CfgStop(void);

/** 主循环推进：窗口到时结算并自动关捕获（内部调 PULSE_Poll） */
uint8_t PULSE_CfgPoll(void);

/** 诊断：丢边沿（中断里发现标志被覆盖）的次数 */
uint32_t PULSE_CfgLostEdges(void);

#endif /* __PULSE_CFG_H */
