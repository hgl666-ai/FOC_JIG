/**
  ******************************************************************************
  * @file    enc_cap.h
  * @brief   ⑤ 编码器回环采集（**U2 专用**）：数 CN2 的 A/B/Z 上有多少个边沿
  *
  * 为什么不用 `pulse_cap` / `PULSE_XCHK`
  * ------------------------------------
  * `pulse_cap.c` 是**单例**，而 U2 的滚动窗口一直在采 MA_IN 组（③④ 要用）。
  * 编码器采集只关心**个数**（不需要周期/占空比），所以本模块用**自己的一套计数器**，
  * 于是两组可以**同时**采 —— 不用做"采集源切换"，也不用动 ARM 的语义。
  * 代价：只给边沿数，不给周期/占空比（⑤ 不需要）。
  *
  * 硬件（见 docs/00 §3.5）
  * ----------------------
  *   CN2 的 A/B/Z → U2 的 PB8/PB7/PB6 = TIM4_CH3/CH2/CH1
  *   （**U1 也挂在这三根线上**；U1 发的时候是 AF 推挽输出，U2 这边保持输入。
  *     两片不能同时驱动，见 docs/12 §2 与 docs/15 §9。）
  *
  * 数边沿的方式与 `pulse_cfg.c` 一致：**单通道 + 每个边沿翻转极性**，
  * 这样上升沿和下降沿都算一个 —— 一个完整脉冲 = 2 个边沿，
  * 和 DUT 那边"计数语义"对齐（docs/15 §7.9）。
  *
  * ⚠ 输入捕获的标志是**读 CCR 就自动清**（不像输出比较要写 0 清）——
  *   这一点和 `enc_gen.c` 正好相反，两边都踩过一次，别再搞混。
  ******************************************************************************
  */
#ifndef __ENC_CAP_H
#define __ENC_CAP_H

#include <stdint.h>
#include "uart_link.h"      /* link_enc_cnt_t */

/**
  * @brief  配好 TIM4 输入捕获并**一直使能**（自由运行计数）
  * @note   上电初始化时调一次。计数器会一直跑，所以"什么时候清零"由调用方决定
  *         （每次发脉冲之前 `EncCap_Clear()`）。
  */
void    EncCap_Init(void);

/** 清零三个计数器（发脉冲**之前**调；清零前后不受并发影响，见实现注释） */
void    EncCap_Clear(void);

/** 读当前计数（不清零） */
void    EncCap_Read(link_enc_cnt_t *out);

/** 计数是否已使能（诊断用；正常恒为 1） */
uint8_t EncCap_Enabled(void);

/** 关掉捕获中断（只有在怀疑它干扰别的功能时才用；正常不要关） */
void    EncCap_Stop(void);

#endif /* __ENC_CAP_H */
